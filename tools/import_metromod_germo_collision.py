def sha(data): return hashlib.sha256(data).hexdigest()


def body(text, name, types):
    pattern = r'(?:public|private) void ' + name + r'\(' + ', '.join(t + r' var\d+' for t in types) + r'\) \{'
    matches = list(re.finditer(pattern, text))
    if len(matches) != 1: raise ValueError('Missing/ambiguous method ' + name)
    start = matches[0].end(); depth = 1; end = start
    while depth:
        if text[end] == '{': depth += 1
        if text[end] == '}': depth -= 1
        end += 1
    return text[start:end-1]


def fields(text):
    for old, new in FIELDS.items(): text = text.replace('var1.' + old, 's.' + new)
    return text.replace('Vector3f', 'V')


def component(text):
    text = fields(text)
    mode = 'jjjjIiijiiIlljllilIjliijlijIIIiI.' + PUT + '.' + REMOVE
    text = text.replace('s.blockMode == ' + mode, 's.blockMode')
    text = text.replace(ROTATE + '(', 'rotate(')
    for old,new in [(REMOVE,'rotateX'),(TICK,'rotateZ')]:
        text=text.replace('jIjijIiIiililljjjiIljilliIijlliI.'+old+'(',new+'(')
    for old, new in [(PUT, 'place'), (REMOVE, 'remove')]:
        text = text.replace('this.'+old+'(var2, ', 'sink.'+new+'(')
    text = text.replace(', '+BLOCK+')', ')')
    text = text.replace('this.'+HELPER+'(var1, var2, var3, var4, var5)', 'move(s, sink, var3, var4, var5)')
    text = text.replace('this.'+PUT, 'width')
    for n in (3,4,5): text = re.sub(r'\bvar'+str(n)+r'\b', ['x','y','z'][n-3], text)
    return text


def tick(text):
    text = fields(text)
    text = text.replace('iIliIlIjjliijjliiljiiIIliIjijlii.'+REMOVE+'()', 'delta40')
    text = re.sub(r'      '+WORLD+r' var3 = [^\n]+;\n', '', text)
    text = re.sub(r'      iljlIillijIljjIjjIilIIljljljjllj var4 = [^\n]+;\n', '', text)
    # Audio is not collision; delete only the reviewed inert sound callback.
    text = re.sub(r'this\.'+PUT+r'\(this\.\w+, var1, var3\);', '/* sound handled by adapter */', text)
    text = re.sub(r'var3\.IlijlIlilIIjlilIlliljjiIljjlIjIi\([^\n]+?\)', 's.powered', text)
    text = text.replace('var3.IlijIjliliIjIlljIIIlIllIljllIIii', 'false')  # server callback branch
    prefix = 'var1.jljiIijIIIIIIliijijjiIjIjiIljjjl.jiljlIIiIiIiIjjjijIIiIiIjjIlljii.'
    for old,new in [(TICK,'towardClosed'),(CLOSE,'towardOpen')]:
        text = re.sub(re.escape(prefix+old)+r'\([^;]+\);', new+'(s, sink, 0, 0, 0);', text)
    text = text.replace('this.'+REMOVE, 'open').replace('this.'+TICK, 'closed')
    return text


def validate(text):
    # All obfuscated identifiers must have been translated, not silently skipped.
    unknown = re.findall(r'\b[Ilij]{20,}\b|\bvar1\b', text)
    if unknown: raise ValueError('Unmapped donor symbol(s): '+str(sorted(set(unknown))))


HEADER = '''package ru.metrocraft.port.metromod.decor;

/** GENERATED by tools.import_metromod_germo_collision; do not edit.
 * Literal donor block-mode arithmetic/callbacks, independent of Minecraft/OBJ.
 * Connected through DonorGermoMotion/DonorGermoCollision. See provenance report.
 * Sink MUST place only into air and remove only a matching, owned block.
 * A callback may place AND remove; order/history must not be flattened to AABBs.
 */
public abstract class DonorGermoBlockRules {
    public static final class V {
        public float x, y, z;
        public V(float x,float y,float z) {this.x=x;this.y=y;this.z=z;}
        public V(V v) {this(v.x,v.y,v.z);}
    }
    public static final class State {
        public V animation=new V(0,0,0), previous=new V(0,0,0);
        public V rotation=new V(0,0,0), scale=new V(1,1,1);
        public boolean blockMode=true, activated, powered;
        public boolean[] segments;
    }
    public interface Sink {
        void place(int x,int y,int z);
        void remove(int x,int y,int z);
    }
    public final V open, closed;
    public final int segmentCount;
    protected int width=6;
    protected DonorGermoBlockRules(V open,V closed,int segmentCount) {
        this.open=open;this.closed=closed;this.segmentCount=segmentCount;
    }
    /** Exact donor yaw rotation: float extrema and Math.round happen AFTER it. */
    public static void rotate(V v,double angle) {
        float x=(float)(Math.cos(angle)*(double)v.x+Math.sin(angle)*(double)v.z);
        v.z=(float)(-Math.sin(angle)*(double)v.x+Math.cos(angle)*(double)v.z);v.x=x;
    }
    private static void rotateX(V v,double a) {
        float y=(float)(Math.cos(a)*(double)v.y-Math.sin(a)*(double)v.z);
        v.z=(float)(Math.sin(a)*(double)v.y+Math.cos(a)*(double)v.z);v.y=y;
    }
    private static void rotateZ(V v,double a) {
        float x=(float)(Math.cos(a)*(double)v.x-Math.sin(a)*(double)v.y);
        v.y=(float)(Math.sin(a)*(double)v.x+Math.cos(a)*(double)v.y);v.x=x;
    }
    /** delta40 = elapsed seconds * 40, not Minecraft partialTicks. */
    public abstract void tick(State s,Sink sink,float delta40);
    public abstract void towardClosed(State s,Sink sink,int x,int y,int z);
    public abstract void towardOpen(State s,Sink sink,int x,int y,int z);
'''


def generate(client, decompiled):
    client=Path(client); decompiled=Path(decompiled)
    if sha(client.read_bytes()) != SHA: raise ValueError('Unexpected donor client')
    ps=json.loads((RES/'metromod_gates.json').read_text())+json.loads((RES/'metromod_interactive.json').read_text())
    models={p['source']+'.m2033model':p['id'] for p in ps if p.get('kind','Germo')=='Germo'}
    generated=[]; rows=[]; hashes={}; decomp_hashes={}
    with zipfile.ZipFile(client) as z:
        def source(cls):
            data=(decompiled/(cls.split('/')[-1]+'.java')).read_bytes()
            hashes[cls+'.class']=sha(z.read(cls+'.class')); decomp_hashes[cls+'.java']=sha(data)
            if REPORT.exists():
                pinned=json.loads(REPORT.read_text()).get('decompiled_sha256',{}).get(cls+'.java')
                if pinned is not None and pinned != sha(data): raise ValueError('Unreviewed decompiler input: '+cls)
            return data.decode()
        source('null/'+BASE)
        for cls in ['iIllIijlIIiijIiIjIliiIlIilIjjlij','ilijlljlIIjjIIlIIjjIiIiilijIIIil']:
            source('null/'+cls)
        cls='null/iIllIijlIIiijIiIjIliiIlIilIjjlij$1.class';hashes[cls]=sha(z.read(cls))
        for cls in [STATE,'lIjijlilIlIIIiIiIlIIIIlIijljllij','IijIjjillljIIIiiiIilIljilIiIIIii','llliilIIjjliIijlilljIliiljIliIjl','jlIIiljjljllljjIIiiijliljiijIili']:
            source('null/'+cls)
        source('null/jIiiIlljjiIliijjiiIlljIjiiiIIlIj')
        source('null/jlIjiliIjjiIiillillilijjjjiIljjI')
        source('null/jIjijIiIiililljjjiIljilliIijlliI')
        for e in catalogue(instructions(read_class(z,CATALOG))[2],kind_fields(read_class(z,KINDS))):
            if e['model'] not in models: continue
            cs=[c['class'] for c in e['profile']['components']]
            comp=next(c for c in cs if read_class(z,c).super_.name.value=='null/'+BASE)
            beh=next(c for c in cs if c!=comp)
            ct=source(comp); bt=source(beh)
            vectors=[]
            for name in (REMOVE,TICK):
                matches=re.findall(r'this\.'+name+r' = new Vector3f\(([^;]+)\);',bt)
                if len(matches)!=1: raise ValueError('Unexpected endpoints')
                if not re.fullmatch(r'[-\d.F, ]+',matches[0]): raise ValueError('Nonliteral endpoints')
                vectors.append(matches[0])
            count=re.findall(r'this\.'+PUT+r'\(var1, (\d+)\);',bt)
            if len(count)!=1: raise ValueError('Unexpected segment count')
            name='Rule'+str(len(rows)+1)
            chunks=['    private static final class '+name+' extends DonorGermoBlockRules {',
                    '        '+name+'() {super(new V('+vectors[0]+'),new V('+vectors[1]+'),'+count[0]+');}']
            for method,out in [(TICK,'towardClosed'),(CLOSE,'towardOpen')]:
                text=component(body(ct,method,[STATE,WORLD,'int','int','int']));validate(text)
                chunks.append('        public void '+out+'(State s,Sink sink,int x,int y,int z) {'+text+'        }')
            if 'private void '+HELPER in ct:
                text=component(body(ct,HELPER,[STATE,WORLD,'int','int','int']));validate(text)
                chunks.append('        private void move(State s,Sink sink,int x,int y,int z) {'+text+'        }')
            text=tick(body(bt,TICK,[STATE]));validate(text)
            chunks.append('        public void tick(State s,Sink sink,float delta40) {'+text+'        }\n    }')
            generated.append('\n'.join(chunks))
            rows.append(dict(id=models[e['model']],source=e['model'],behavior=beh,component=comp,
                             generated_class=name,segments=int(count[0]),open=vectors[0],closed=vectors[1],
                             catalogue_args=[(a['args'] if a.get('class')=='org/lwjgl/util/vector/Vector3f' else {'static':a['static']}) if isinstance(a,dict) else a for a in e['profile']['args']]))
    if len(rows)!=17: raise ValueError('Germo coverage changed')
    factory='    public static DonorGermoBlockRules get(String id) {\n        switch(id) {\n'
    for row in rows: factory+='            case "'+row['id']+'":return new '+row['generated_class']+'();\n'
    factory+='            default:throw new IllegalArgumentException("Unknown Germo: "+id);\n        }\n    }\n'
    output=HEADER+factory+'\n\n'.join(generated)+'\n}\n'
    report=dict(client_sha256=SHA,class_sha256=hashes,fernflower_version='npm fernflower@1.1.0',
                decompiled_sha256=decomp_hashes,profiles=rows,profile_count=len(rows),
                generated_java_sha256=sha(output.encode()),runtime_connected=True,
                coordinate_adapter_verified=False,coordinate_adapter_math_verified=True,minecraft_gameplay_verified=False,
                coordinate_adapter='Block-mode renderer factory selects ilijlljlIIjjIIlIIjjIiIiilijIIIil: T(state) R(y,x,z) T(catalogue offset) S(catalogue scale * instance scale), no implicit .5. Canonical map translation=0/scale=1; invert catalogue transform on rounded grid cubes, then apply MinETRO unit ground/offset/facing.',
                adaptations=['server branch only','sound callback omitted','world writes replaced by ordered Sink callbacks'],
                caveats=['Sink must enforce air-only placement and UUID-safe removal',
                         'Initial world blocks are map state, not supplied by client.jar',
                         'Lifecycle initializes only animation.x; do not invent y initialization',
                         'History and segment flags must persist; reversals are not a function of progress alone'])
    return output,report


def run(client,decompiled):
    output,report=generate(client,decompiled)
    metadata={}
    for p in report['profiles']:
        a=p['catalogue_args'];scale=a[3]
        if isinstance(scale,dict):
            if scale!={'static':'null/IijIjjillljIIIiiiIilIljilIiIIIii.jjlliijIIIiIjIjiiIjijjIjIljjiiII'}:raise ValueError('Unknown scale reference')
            scale=[1,1,1]
        metadata[p['id']]={'offset':a[2],'scale':scale}
    (RES/'metromod_germo_collision.json').write_text(json.dumps(metadata,indent=2)+'\n')
    OUTPUT.write_text(output);REPORT.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    return report

