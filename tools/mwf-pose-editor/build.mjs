import {build} from 'esbuild';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {zipSync,strToU8} from 'fflate';
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'../..');
const pack=readFileSync(path.join(root,'downloads/Metro_Uboinik_MWF_fix1_v5.zip'));
const result=await build({entryPoints:[path.join(here,'app.mjs')],bundle:true,minify:true,write:false,format:'iife',target:['chrome100','firefox100','safari16'],define:{__DEFAULT_PACK_B64__:JSON.stringify(pack.toString('base64'))}});
const js=result.outputFiles[0].text.replaceAll('</script','<\\/script');
const css=readFileSync(path.join(here,'style.css'),'utf8');
const html=readFileSync(path.join(here,'index.html'),'utf8').replace('/*__STYLE__*/',()=>css).replace('/*__APP__*/',()=>js);
const out=path.join(root,'artifacts/mwf-pose-editor');mkdirSync(out,{recursive:true});writeFileSync(path.join(out,'index.html'),html);
const readme=readFileSync(path.join(here,'README_RU.txt'));
const zip=zipSync({'MWF_Pose_Editor.html':strToU8(html),'ИНСТРУКЦИЯ.txt':new Uint8Array(readme),'LICENSE_THREE.txt':new Uint8Array(readFileSync(path.join(here,'node_modules/three/LICENSE'))),'LICENSE_FFLATE.txt':new Uint8Array(readFileSync(path.join(here,'node_modules/fflate/LICENSE')))},{level:9});
mkdirSync(path.join(root,'downloads'),{recursive:true});writeFileSync(path.join(root,'downloads/MWF_Pose_Editor_v1.zip'),zip);
console.log('Offline HTML:',Buffer.byteLength(html),'bytes; downloadable ZIP:',zip.length,'bytes');
